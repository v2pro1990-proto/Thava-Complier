"""Build the embedded key.press runtime for native and C++ targets."""
from pathlib import Path
import subprocess
import tempfile

root = Path(__file__).resolve().parents[1] / "src"

def run(*args):
    return subprocess.check_output(args, text=True)

targets = {
    "x64": ("", "-m64", "elf_x86_64", ["-mno-sse", "-mno-sse2", "-mno-mmx"]),
    "i686": ("", "-m32", "elf_i386", ["-march=i686", "-mno-sse", "-mno-mmx",
                                    "-mpreferred-stack-boundary=2", "-mincoming-stack-boundary=2"]),
    "arm64": ("aarch64-linux-gnu-", "-march=armv8-a", "aarch64linux", ["-ffixed-x18"]),
}
header = [
    "#pragma once", "", "#include <cstdint>", "",
    "// Generated by tools/generate_key_press.py.", "namespace key_press_runtime {",
]
with tempfile.TemporaryDirectory() as temporary:
    work = Path(temporary)
    script = work / "runtime.ld"
    script.write_text(
        "SECTIONS { . = 0; .runtime : { *(.text .text.*) *(.rodata .rodata.*) "
        "*(.data.rel.ro*) *(.got .got.*) } /DISCARD/ : { *(.comment .note* .eh_frame*) } }\n",
        encoding="ascii",
    )
    for arch, (prefix, flag, emulation, extra) in targets.items():
        for mode in ("Linux", "Windows"):
            name = arch + mode
            obj, elf, blob = map(str, (work / "runtime.o", work / "runtime.elf", work / "runtime.bin"))
            platform = ["-DTHAVA_KEY_WINDOWS"] if mode == "Windows" else []
            run(prefix + "gcc", flag, *extra, *platform, "-Os", "-std=c11", "-fPIC", "-ffreestanding",
                "-fno-builtin", "-fno-stack-protector", "-fno-jump-tables", "-fno-asynchronous-unwind-tables",
                "-fcf-protection=none", "-DTHAVA_KEY_NATIVE", "-c", str(root / "key_press.c"), "-o", obj)
            run(prefix + "ld", "-m", emulation, "-T", str(script), "-e", "thava_key_press", obj, "-o", elf)
            if run(prefix + "nm", "-u", elf).strip():
                raise RuntimeError(f"Unexpected runtime imports for {name}")
            run(prefix + "objcopy", "-O", "binary", "-j", ".runtime", elf, blob)
            data = Path(blob).read_bytes()
            offset, = [int(line.split()[0], 16) for line in run(prefix + "nm", elf).splitlines()
                       if line.endswith(" T thava_key_press")]
            if not 0 <= offset < len(data):
                raise RuntimeError(f"Invalid entry address for {name}")
            header.append(f"inline constexpr uint32_t {name}Entry = 0x{offset:x};")
            header.append(f"inline constexpr uint8_t {name}[] = {{")
            for pos in range(0, len(data), 16):
                header.append("    " + ", ".join(f"0x{x:02x}" for x in data[pos:pos+16]) + ",")
            header.append("};")

spec = (root / "key_press.h").read_text(encoding="ascii").removeprefix("#pragma once\n")
body = (root / "key_press.c").read_text(encoding="ascii").removeprefix('#include "key_press.h"\n')
header.extend(['inline constexpr char cppSource[] = R"key_press(', spec, body, ')key_press";', "}", ""])
(root / "key_press_data.hpp").write_text("\n".join(header), encoding="ascii")
