"""Generate Thava's freestanding native decimal routines and C++ source."""

from pathlib import Path
import subprocess
import tempfile

root = Path(__file__).resolve().parents[1]
src = root / "src"
source = src / "decimal_runtime.c"


def run(*args):
    return subprocess.check_output(args, text=True)


targets = {
    "x64": ("", "-m64", "elf_x86_64", ("-mno-sse", "-mno-sse2", "-mno-mmx")),
    "i686": ("", "-m32", "elf_i386", ("-march=i686", "-mno-sse", "-mno-mmx")),
    "arm64": ("aarch64-linux-gnu-", "-march=armv8-a", "aarch64linux", ("-ffixed-x18",)),
}

header = [
    "#pragma once", "", "#include <cstdint>", "",
    "// Generated by tools/generate_decimal_runtime.py.",
    "namespace decimal_runtime {",
]

with tempfile.TemporaryDirectory() as temporary:
    work = Path(temporary)
    script = work / "decimal.ld"
    script.write_text(
        "SECTIONS { . = 0; .runtime : { *(.text .text.*) "
        "*(.rodata .rodata.*) *(.got .got.*) } "
        "/DISCARD/ : { *(.comment .note* .eh_frame*) } }\n",
        encoding="ascii",
    )
    for name, (prefix, arch, emulation, platform_flags) in targets.items():
        obj, elf, blob = (str(work / ("decimal." + ext)) for ext in ("o", "elf", "bin"))
        run(prefix + "gcc", arch, *platform_flags, "-Os", "-std=c11", "-fPIC",
            "-ffreestanding", "-fno-builtin", "-fno-stack-protector", "-fno-jump-tables",
            "-fno-asynchronous-unwind-tables", "-DTHAVA_DECIMAL_NATIVE", "-c", str(source), "-o", obj)
        run(prefix + "ld", "-m", emulation, "-T", str(script), "-e", "thava_decimal_run", obj, "-o", elf)
        if run(prefix + "nm", "--undefined-only", elf).strip():
            raise RuntimeError(f"Unexpected runtime imports for {name}")
        run(prefix + "objcopy", "-O", "binary", "-j", ".runtime", elf, blob)
        data = Path(blob).read_bytes()
        offset, = [
            int(address, 16) for address, kind, symbol in
            (line.split() for line in run(prefix + "nm", "--defined-only", elf).splitlines())
            if kind == "T" and symbol == "thava_decimal_run"
        ]
        if not 0 <= offset < len(data):
            raise RuntimeError(f"Runtime entry outside the blob for {name}")
        header.append(f"inline constexpr uint32_t {name}Entry = 0x{offset:x};")
        header.append(f"inline constexpr uint8_t {name}[] = {{")
        for pos in range(0, len(data), 16):
            header.append("    " + ", ".join(f"0x{byte:02x}" for byte in data[pos:pos + 16]) + ",")
        header.append("};")

spec = (src / "decimal_spec.h").read_text(encoding="utf-8").removeprefix("#pragma once\n")
body = source.read_text(encoding="utf-8").removeprefix('#include "decimal_spec.h"\n')
header.extend(['inline constexpr char cppSource[] = R"decimal(', spec, body, ')decimal";', "}"])
(src / "decimal_runtime_data.hpp").write_text("\n".join(header) + "\n", encoding="utf-8")
